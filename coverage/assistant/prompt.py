def visible(point, bounds):
    return not bounds or (bounds[0] <= point[0] <= bounds[2] and bounds[1] <= point[1] <= bounds[3])


def summarize_view(data, bounds):
    cells = [c for c in data["cells"] if visible(c["c"], bounds)]
    counted = [c for c in cells if c["counted"]]
    return {
        "cells": len(cells),
        "colors": dict(Counter(c["cls"] for c in counted)),
        "worst": [{"id": c["id"], "median": c["m"]} for c in sorted(counted, key=lambda c: c["m"])[:5]],
        "candidates": [c["id"] for c in data["candidates"] if visible((c["lat"], c["lon"]), bounds)],
    }
